{-# LANGUAGE GADTs #-}

-- | Урок 1. Расширение GADTs.
--
-- Читать сверху вниз. Всё, что тут есть, можно потрогать в repl:
--
-- > stack repl
-- > ghci> :load Lesson.Gadts
-- > ghci> eval example1
module Gadts
  ( -- * Шаг 0. Обычный data — то, что ты уже знаешь
    Shape (..)
  , area
    -- * Шаг 1. Та же самая запись, но в стиле GADT
  , Shape' (..)
  , area'
    -- * Шаг 2. Зачем это нужно
  , Expr (..)
  , eval
  , example1
  , example2
  ) where

--------------------------------------------------------------------------------
-- Шаг 0. Обычное объявление типа
--------------------------------------------------------------------------------

-- Конструкторы перечислены через |, каждый со своими полями.
data Shape
  = Circle Double
  | Rect Double Double

area :: Shape -> Double
area (Circle r) = pi * r * r
area (Rect w h) = w * h

--------------------------------------------------------------------------------
-- Шаг 1. Тот же тип, записанный как GADT
--------------------------------------------------------------------------------

-- Включается расширением GADTs (прагма в первой строке файла).
--
-- Вместо перечисления через | пишем СИГНАТУРУ каждого конструктора,
-- как будто это обычные функции. Circle' берёт Double и возвращает Shape'.
data Shape' where
  Circle' :: Double -> Shape'
  Rect' :: Double -> Double -> Shape'

-- Сопоставление с образцом не изменилось вообще.
area' :: Shape' -> Double
area' (Circle' r) = pi * r * r
area' (Rect' w h) = w * h

-- ВАЖНО: Shape и Shape' — это один и тот же тип, просто две записи.
-- Пока никакой новой силы мы не получили. Она появляется на шаге 2.

--------------------------------------------------------------------------------
-- Шаг 2. Ради чего всё затевалось
--------------------------------------------------------------------------------

-- Задача: описать маленький язык выражений — числа, сравнение, if.
--
-- Попробуем обычным data:
--
--   data BadExpr
--     = IntLit Int
--     | BoolLit Bool
--     | Add BadExpr BadExpr
--
-- Две проблемы:
--   1. Add (IntLit 1) (BoolLit True) прекрасно компилируется. Чушь, но
--      компилятор о ней не знает — ловить придётся в рантайме.
--   2. Что вернёт вычислитель? Иногда Int, иногда Bool. Пришлось бы
--      заводить обёртку data Value = VInt Int | VBool Bool и всюду её
--      распаковывать.
--
-- Теперь то же самое с GADT. Добавляем к типу параметр a — «что вернёт
-- это выражение», и каждый конструктор указывает своё конкретное a:

data Expr a where
  IntLit :: Int -> Expr Int
  BoolLit :: Bool -> Expr Bool
  Add :: Expr Int -> Expr Int -> Expr Int
  IsZero :: Expr Int -> Expr Bool
  If :: Expr Bool -> Expr a -> Expr a -> Expr a

-- Вот это и есть ВСЁ отличие GADT от обычного data:
-- при обычном объявлении все конструкторы обязаны вернуть Expr a
-- с одной и той же переменной a. Здесь каждый возвращает что хочет.

-- Теперь бессмыслица не собирается. Раскомментируй и посмотри ошибку:
--
-- broken :: Expr Int
-- broken = Add (IntLit 1) (BoolLit True)
--
--   • Couldn't match type ‘Bool’ with ‘Int’
--       Expected: Expr Int
--         Actual: Expr Bool

-- А вычислитель пишется без всяких обёрток:
eval :: Expr a -> a
eval (IntLit n) = n
eval (BoolLit b) = b
eval (Add x y) = eval x + eval y
eval (IsZero x) = eval x == 0
eval (If c t f) = if eval c then eval t else eval f

-- ГЛАВНЫЙ МОМЕНТ, из-за которого это работает.
--
-- Посмотри на первую строку eval. Тип обещает вернуть a — что угодно.
-- А возвращается n, то есть Int. Почему компилятор не ругается?
--
-- Потому что мы сопоставились с IntLit, а такой конструктор бывает
-- ТОЛЬКО у Expr Int. Значит внутри этой ветки a и есть Int — компилятор
-- это выводит и пользуется. В каждой ветке a своё.
--
-- Формулировка на будущее: сопоставление с образцом по GADT даёт
-- информацию не только о значении, но и о типах.

example1 :: Expr Int
example1 = Add (IntLit 2) (IntLit 3)

example2 :: Expr Int
example2 = If (IsZero (IntLit 0)) (IntLit 1) (IntLit 99)

