--
-- Вот откуда в effectful берётся запись Eff '[IOE] a: это тип Eff,
-- которому передали СПИСОК ТИПОВ-эффектов. И там же DispatchOf Logger =
-- Dynamic — Dynamic это конструктор обычного типа Dispatch, поднятый
-- на уровень типов ровно так же, как здесь Opened и Closed.

