-- $kinds
-- Виды — это «типы типов». Проверяется в repl командой @:kind@:
--
-- > ghci> :kind Int
-- > Int :: *            -- готовый тип, значения бывают
-- > ghci> :kind Maybe
-- > Maybe :: * -> *     -- ещё не тип: дай ему тип, получишь тип
-- > ghci> :kind Maybe Int
-- > Maybe Int :: *
--
-- Звёздочка — старое написание вида обычных типов. В новых диалектах
-- языка то же самое пишут словом Type; в этом проекте включён
-- Haskell2010, поэтому ghci печатает *.
--
-- До сих пор на уровне типов жили ТОЛЬКО типы. DataKinds добавляет туда
-- обычные значения.

--------------------------------------------------------------------------------
-- Шаг 1. Проблема: параметр-фантом принимает что попало
--------------------------------------------------------------------------------

-- Хотим тип «дверь», у которой в типе записано, открыта она или закрыта.
-- Первая попытка — параметр, который нигде не используется в полях
-- (такой называют фантомным):

newtype Sloppy s = Sloppy String

-- Беда в том, что s — это любой тип. Всё это компилируется:
--
--   Sloppy "дверь" :: Sloppy Int
--   Sloppy "дверь" :: Sloppy (Maybe [String])
--
-- Компилятор не мешает написать бессмыслицу, потому что мы нигде не сказали,
-- какие значения параметр вообще может принимать.

--------------------------------------------------------------------------------
-- Шаг 2. DataKinds: свой набор допустимых значений на уровне типов
--------------------------------------------------------------------------------

-- Объявляем самый обычный тип с двумя значениями:
data DoorState = Opened | Closed

-- Прагма DataKinds в шапке файла «поднимает» это объявление на уровень выше:
--   * DoorState, который был типом, становится ВИДОМ;
--   * Opened и Closed, которые были значениями, становятся ТИПАМИ этого вида.
--
-- Проверяется в repl:
--
--   ghci> :kind Opened
--   Opened :: DoorState
--
-- Теперь можно потребовать, чтобы параметр был именно из этого набора.
-- Запись (s :: DoorState) — это kind-сигнатура, отсюда вторая прагма файла:

newtype Door (s :: DoorState) = Door String

-- И теперь Door Int не компилируется:
--
--   • Expected kind ‘DoorState’, but ‘Int’ has kind ‘*’
--
-- Заметь: значений типа Opened не существует и существовать не может.
-- Эти «типы» нужны исключительно компилятору как метки.

frontDoor :: Door Closed
frontDoor = Door "входная"

-- Самое интересное — состояние можно требовать и менять в сигнатурах.
-- openDoor принимает ТОЛЬКО закрытую дверь и возвращает открытую:
openDoor :: Door Closed -> Door Opened
openDoor (Door name) = Door name

closeDoor :: Door Opened -> Door Closed
closeDoor (Door name) = Door name

-- Дважды открыть дверь теперь невозможно — не скомпилируется:
--
--   broken = openDoor (openDoor frontDoor)
--
--   • Couldn't match type ‘Opened’ with ‘Closed’
--       Expected: Door Closed
--         Actual: Door Opened
--
-- Это называется «состояние в типах»: неправильный порядок вызовов
-- становится ошибкой компиляции, а не багом в рантайме.

-- А если состояние неважно — оставляем параметр переменной:
describe :: Door s -> String
describe (Door name) = "дверь: " <> name

--------------------------------------------------------------------------------
